// electron-builder 动态配置：EDITION=community 普通版（无联机、不带 easytier，体积更小）；
// EDITION=sponsor（缺省）赞助版（含陶瓦联机与内置 easytier 内核）。
// 用法：$env:EDITION='community'; npx electron-builder --win nsis --x64 --config electron-builder.cjs
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');
const edition = process.env.EDITION === 'community' ? 'community' : 'sponsor';

// 单一事实来源：打包时把 edition 写进主进程读取的 generated 文件，
// 避免上一次构建残留 community 导致赞助版主进程跳过 lan.cjs（表现为“未找到内置联机内核”）
fs.writeFileSync(
  path.join(__dirname, 'electron', 'edition.generated.cjs'),
  `// AUTO-GENERATED BY electron-builder.cjs. Do not edit by hand.\nmodule.exports = { edition: '${edition}' };\n`,
  'utf8',
);

const common = {
  appId: 'com.glowstone.launcher',
  productName: 'Glowstone Launcher',
  asar: true,
  // 直接复用本机 node_modules/electron/dist（版本 22.3.27），打包时不再从 GitHub 下载 electron，
  // 避免国内网络连 GitHub 超时（connect ETIMEDOUT 20.205.243.166）。
  electronDist: path.join(__dirname, 'node_modules', 'electron', 'dist'),
  directories: { output: 'release' },
  files: [
    'dist/**/*',
    'electron/**/*',
    'package.json',
    '!node_modules/**/*',
    '!**/node_modules/**/*',
  ],
  win: {
    target: [{ target: 'nsis', arch: ['x64'] }],
    icon: 'build/icon.ico',
  },
  nsis: {
    oneClick: false,
    perMachine: false,
    allowElevation: true,
    allowToChangeInstallationDirectory: true,
    createDesktopShortcut: true,
    createStartMenuShortcut: true,
    shortcutName: 'Glowstone Launcher',
    menuCategory: false,
    installerLanguages: ['zh_CN', 'en_US'],
    language: '2052',
    include: 'build/installer.nsh',
    differentialPackage: false,
  },
  electronLanguages: ['zh-CN', 'en-US'],
  compression: 'maximum',
};

const cfg = {
  ...common,
  // 普通版连开服/联机后端源文件也不打进 asar（前端页面已别名空桩），做到普通版彻底不含这些功能
  files:
    edition === 'community'
      ? [...common.files, '!electron/lan.cjs', '!electron/server.cjs']
      : common.files,
  nsis: {
    ...common.nsis,
    artifactName:
      edition === 'community'
        ? 'GlowstoneLauncher.${ext}'
        : 'GlowstoneLauncher陶瓦联机版赞助版.${ext}',
  },
  extraResources: [
    // 圆角脚本必须在 asar 外：外部 powershell.exe 无法读取 app.asar 归档内的文件
    { from: 'electron/shape-window.ps1', to: 'shape-window.ps1' },
    ...(edition === 'sponsor'
      ? [{ from: 'resources/easytier', to: 'easytier', filter: ['**/*'] }]
      : []),
  ],
  // 每次打包前，按当前 EDITION 用正确的 VITE_EDITION 重新构建前端 dist。
  // 否则两版会共用同一份 dist：普通版也会带上赞助版的“陶瓦联机”页面（HAS_LAN=true），
  // 表现为“普通版安装包装出来是赞助版”。Rollup 仅在 VITE_EDITION=community 时摇除联机代码。
  beforeBuild: async () => {
    const viteBin = path.join(__dirname, 'node_modules', 'vite', 'bin', 'vite.js');
    execFileSync(process.execPath, [viteBin, 'build'], {
      stdio: 'inherit',
      cwd: __dirname,
      env: { ...process.env, VITE_EDITION: edition },
    });
    // 返回 undefined：node_modules 仍交给 electron-builder 默认重建流程。
  },
};

console.log(`[electron-builder] edition=${edition} artifact=${cfg.nsis.artifactName} easytier=${edition === 'sponsor'}`);
module.exports = cfg;
